/**
 * Draws the seed maps from Natural Earth (public domain, naturalearthdata.com) into
 * src/seed/maps/*.svg. Run once when the maps change: `pnpm tsx scripts/build-seed-maps.ts`.
 * The output is committed, so seeding needs no network. No labels: the maps must not give
 * the answers away.
 */
import { writeFile } from 'node:fs/promises';
import {
  mapHeight,
  project,
  TURKIYE_MAP,
  WORLD_MAP,
  type SeedMap,
} from '../src/seed/maps/projection.js';

const BASE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson';

type Ring = [number, number][];
interface Feature {
  properties: Record<string, unknown>;
  geometry:
    { type: 'Polygon'; coordinates: Ring[] } | { type: 'MultiPolygon'; coordinates: Ring[][] };
}

const COLORS = {
  sea: '#123553',
  land: '#2c4733',
  border: '#0b1f30',
  home: '#4f8a55',
  lake: '#123553',
};

async function load(name: string): Promise<Feature[]> {
  const response = await fetch(`${BASE}/${name}.geojson`);
  if (!response.ok) throw new Error(`${name}: ${response.status}`);
  return ((await response.json()) as { features: Feature[] }).features;
}

function polygons(feature: Feature): Ring[][] {
  return feature.geometry.type === 'Polygon'
    ? [feature.geometry.coordinates]
    : feature.geometry.coordinates;
}

/** SVG path of a feature in map pixels: rounded, near-duplicate points and tiny rings dropped. */
function pathOf(map: SeedMap, feature: Feature): string {
  const width = map.width;
  const height = mapHeight(map);
  const margin = 0.05;
  const parts: string[] = [];
  for (const polygon of polygons(feature)) {
    for (const ring of polygon) {
      const points = ring.map(([lon, lat]) => project(map, lat, lon));
      const inside = points.some(
        (p) => p.x > -margin && p.x < 1 + margin && p.y > -margin && p.y < 1 + margin,
      );
      if (!inside) continue;
      const kept: string[] = [];
      let last: { x: number; y: number } | null = null;
      for (const p of points) {
        const x = Math.round(p.x * width);
        const y = Math.round(p.y * height);
        if (last && Math.hypot(x - last.x, y - last.y) < 2) continue;
        kept.push(`${x} ${y}`);
        last = { x, y };
      }
      if (kept.length >= 3) parts.push(`M${kept.join('L')}Z`);
    }
  }
  return parts.join('');
}

function svg(map: SeedMap, body: string[]): string {
  const height = mapHeight(map);
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${map.width}" height="${height}" viewBox="0 0 ${map.width} ${height}">`,
    `<!-- Natural Earth (public domain). Generated by scripts/build-seed-maps.ts -->`,
    `<rect width="${map.width}" height="${height}" fill="${COLORS.sea}"/>`,
    ...body,
    '</svg>',
    '',
  ].join('\n');
}

function countries(map: SeedMap, features: Feature[], home: string | null): string[] {
  return features.flatMap((feature) => {
    const d = pathOf(map, feature);
    if (!d) return [];
    const fill = feature.properties.ADM0_A3 === home ? COLORS.home : COLORS.land;
    return [
      `<path fill="${fill}" stroke="${COLORS.border}" stroke-width="1.5" stroke-linejoin="round" d="${d}"/>`,
    ];
  });
}

function lakes(map: SeedMap, features: Feature[]): string[] {
  return features.flatMap((feature) => {
    const d = pathOf(map, feature);
    return d ? [`<path fill="${COLORS.lake}" d="${d}"/>`] : [];
  });
}

const detailed = await load('ne_10m_admin_0_countries');
const detailedLakes = await load('ne_10m_lakes');
const coarse = await load('ne_50m_admin_0_countries');

const outDir = new URL('../src/seed/maps/', import.meta.url);
await writeFile(
  new URL(TURKIYE_MAP.file, outDir),
  svg(TURKIYE_MAP, [
    ...countries(TURKIYE_MAP, detailed, 'TUR'),
    ...lakes(TURKIYE_MAP, detailedLakes),
  ]),
);
await writeFile(
  new URL(WORLD_MAP.file, outDir),
  svg(WORLD_MAP, countries(WORLD_MAP, coarse, null)),
);
console.log('maps written');
